def _module_to_path(module: str) -> str | None:
    if module == "openflight" or module.startswith("openflight."):
        parts = module.split(".")
        p = "/".join(parts)
        if os.path.isfile(p + ".py"):
            return p + ".py"
        if os.path.isfile(os.path.join(p, "__init__.py")):
            return os.path.join(p, "__init__.py")
        return None
    top = module.split(".")[0]
    fixture_tops = {os.path.splitext(os.path.basename(r))[0]
                    for r in EV.ARTIFACT_GROUPS["observer_fixtures"]}
    if top in fixture_tops:
        return f"{top}.py"
    return None


def _import_closure(start_path: str | list[str]) -> set[str]:
    """Repo-local files imported (source-level) by start_path, transitively.
    Handles `from pkg import submodule` (module + each imported name) and
    resolves packages to their __init__.py. openflight/cli.py is a leaf:
    its lazy imports are command-scoped."""
    starts = [start_path] if isinstance(start_path, str) else list(start_path)
    seen: set[str] = set()
    stack = list(starts)
    while stack:
        path = stack.pop()
        if path in seen or not os.path.isfile(path):
            continue
        seen.add(path)
        if path in CLOSE_EXEMPT:
            continue
        with open(path) as f:
            tree = ast.parse(f.read(), filename=path)
        for node in ast.walk(tree):
            mods = []
            if isinstance(node, ast.Import):
                mods = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.module:
                mods = [node.module]
                for al in node.names:
                    if al.name != "*":
                        mods.append(f"{node.module}.{al.name}")
            for mod in mods:
                rel = _module_to_path(mod)
                if rel and rel not in seen:
                    stack.append(rel)
    return seen


@pytest.mark.parametrize("check,producer", sorted(PRODUCERS.items()))
def test_graph_declares_every_imported_input(check, producer):
    """Every repo-local module the producing test imports (transitively
    through openflight/* and the root fixtures) must be declared in the
    check's artifact groups. Weights/file reads are covered by the
    mutation rows above; this guards the import side."""
    declared: set[str] = set()
    expanded = EV.expand_groups(".")
    for group in EV.CHECK_DEPS[check]:
        if group in EV.OPTIONAL_GROUPS:
            continue
        declared.update(expanded[group])
    closure = _import_closure(producer)
    missing = closure - declared
    assert not missing, (
        f"check '{check}' imports {sorted(missing)} but the graph does "
        f"not declare them; add them to CHECK_DEPS['{check}'] or fix "
        f"the closure")
