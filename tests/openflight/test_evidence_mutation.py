def test_never_run_checks_and_unverified_claims(tmp_path):
    # repro only runs the six host checks; build/qemu never run in a
    # host-only tree and must report "never run", never "fresh"
    root = _make_sandbox(tmp_path, results_for=REPRO_CHECKS)
    st = EV.status(root=str(root))
    assert st["stale_checks"] == []
    assert st["never_run_checks"] == ["build", "qemu"]
    # C2/C3 (build) and C4/C7/C8 (qemu) have no live evidence
    for c in ("C2", "C3", "C4", "C7", "C8", "C10"):
        assert c in st["claims_unverified"], c
    # claims backed by the six host checks are verified, not at risk
    assert st["claims_at_risk"] == []


def test_record_without_results_never_runs_anything(tmp_path):
    root = _make_sandbox(tmp_path)
    EV.record(root=str(root))  # standalone CLI record: nothing ran
    st = EV.status(root=str(root))
    assert st["never_run_checks"] == ALL_CHECKS
    assert st["stale_checks"] == []


def test_required_input_absent_at_record_is_never_run(tmp_path):
    # a check recorded as ran while a required input was absent gets
    # "never run", not "fresh"
    root = _make_sandbox(tmp_path, results_for=[])
    p = root / "learned_observer.pt"
    p.unlink()
    EV.record(root=str(root), results={"parity": {"result": "ok"}})
    st = EV.status(root=str(root))
    assert "parity" in st["never_run_checks"]
    assert any("absent at record" in r
               for r in st["checks"]["parity"]["reasons"])


# ---------------------------------------------------------------------------
# import-closure derivation guard
# ---------------------------------------------------------------------------

def _module_to_path(module: str) -> str | None:
    if module == "openflight" or module.startswith("openflight."):
        parts = module.split(".")
        return "/".join(parts) + ".py"
    top = module.split(".")[0]
    fixture_tops = {os.path.splitext(os.path.basename(r))[0]
                    for r in EV.ARTIFACT_GROUPS["observer_fixtures"]}
    if top in fixture_tops:
        return f"{top}.py"
    return None


def _import_closure(start_path: str) -> set[str]:
    """Repo-local files imported (source-level) by start_path, transitively.
    openflight/cli.py is a leaf: its lazy imports are command-scoped."""
    seen: set[str] = set()
    stack = [start_path]
    while stack:
        path = stack.pop()
        if path in seen or not os.path.isfile(path):
            continue
        seen.add(path)
        if path in CLOSE_EXEMPT:
            continue
        with open(path) as f:
            tree = ast.parse(f.read(), filename=path)
        for node in ast.walk(tree):
            mods = []
            if isinstance(node, ast.Import):
                mods = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.module:
                mods = [node.module]
            for mod in mods:
                rel = _module_to_path(mod)
                if rel and rel not in seen:
                    stack.append(rel)
    return seen


@pytest.mark.parametrize("check,producer", sorted(PRODUCERS.items()))
def test_graph_declares_every_imported_input(check, producer):
    """Every repo-local module the producing test imports (transitively
    through openflight/* and the root fixtures) must be declared in the
    check's artifact groups. Weights/file reads are covered by the
    mutation rows above; this guards the import side."""
    declared: set[str] = set()
    for group in EV.CHECK_DEPS[check]:
        if group in EV.OPTIONAL_GROUPS:
            continue
        declared.update(EV.ARTIFACT_GROUPS[group])
    closure = _import_closure(producer)
    missing = closure - declared
    assert not missing, (
        f"check '{check}' imports {sorted(missing)} but the graph does "
        f"not declare them; add them to CHECK_DEPS['{check}'] or fix "
        f"the closure")
