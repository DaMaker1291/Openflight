def _make_sandbox(tmp_path, results_for=ALL_CHECKS):
    root = tmp_path / "repo"
    for group, rels in EV.expand_groups(".").items():
        for rel in rels:
            dst = root / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            if os.path.isfile(rel):
                shutil.copy(rel, dst)
            elif group == "generated_cxx":
                dst.write_text("// generated by openflight compile\n")
            elif group == "firmware_binary":
                dst.write_bytes(b"\x7fELF-fake-firmware")
    EV.record(root=str(root),
              results={c: {"result": "ok"} for c in results_for})
    return root


def _mutate(root, rel, transform):
    """Mutate one sandbox file; restore bytes even if status() raises."""
    p = root / rel
    original = p.read_bytes()
    try:
        p.write_bytes(transform(original))
        return EV.status(root=str(root))
    finally:
        p.write_bytes(original)


def _append_comment(data: bytes) -> bytes:
    return data + b"\n# evidence mutation probe\n"


