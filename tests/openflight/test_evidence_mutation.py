"""Evidence-graph mutation table + import-closure derivation (2026-10-15).

Independent probe rows: for each input class, record, mutate ONE file,
run status, assert EXACTLY the checks that read it go stale. All mutations
happen in a tmp-path sandbox copy of the tracked inputs — the real tree is
never touched — and each mutation restores its file in a finally block.

The final test re-derives each check's import closure from its producing
test module and fails if declared inputs drift from what the check
actually imports (file reads like weights are covered by the mutation
rows above; imports are covered here).
"""
