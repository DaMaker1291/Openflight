"""Evidence-graph mutation table + import-closure derivation (2026-10-15).

Independent probe rows: for each input class, record, mutate ONE file,
run status, assert EXACTLY the checks that read it go stale. All mutations
happen in a tmp-path sandbox copy of the tracked inputs — the real tree is
never touched — and each mutation restores its file in a finally block.

The final test re-derives each check's import closure from its producing
test module and fails if declared inputs drift from what the check
actually imports (file reads like weights are covered by the mutation
rows above; imports are covered here).
"""
import ast
import os
import shutil

import pytest

from openflight import evidence as EV

ALL_CHECKS = sorted(EV.CHECK_DEPS)
REPRO_CHECKS = ["battery", "heldout", "independent", "workflows",
                "baseline", "parity"]

# check -> test module that produces its results file
PRODUCERS = {
    "battery": "tests/openflight/test_contract_battery.py",
    "heldout": "tests/openflight/test_heldout_challenge.py",
    "independent": "tests/openflight/test_independent_challenge.py",
    "workflows": "tests/openflight/test_three_workflows.py",
    "baseline": "tests/openflight/test_baseline_compare.py",
    "parity": "tests/openflight/test_firmware_harness.py",
}

# modules imported by checks but not worth transitively closing:
# cli.py is a command dispatcher whose function-level imports belong to
# individual subcommands, not to every check that uses _arch_for_example
CLOSE_EXEMPT = {"openflight/cli.py"}


def _make_sandbox(tmp_path, results_for=ALL_CHECKS):
    root = tmp_path / "repo"
    for group, rels in EV.ARTIFACT_GROUPS.items():
        for rel in rels:
            dst = root / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            if os.path.isfile(rel):
                shutil.copy(rel, dst)
            elif group == "generated_cxx":
                dst.write_text("// generated by openflight compile\n")
            elif group == "firmware_binary":
                dst.write_bytes(b"\x7fELF-fake-firmware")
    EV.record(root=str(root),
              results={c: {"result": "ok"} for c in results_for})
    return root


def _mutate(root, rel, transform):
    """Mutate one sandbox file; restore bytes even if status() raises."""
    p = root / rel
    original = p.read_bytes()
    try:
        p.write_bytes(transform(original))
        return EV.status(root=str(root))
    finally:
        p.write_bytes(original)


def _append_comment(data: bytes) -> bytes:
    return data + b"\n# evidence mutation probe\n"


@pytest.mark.parametrize("rel", [
    "openflight/contract/checker.py",
    "openflight/contract/units.py",
    "openflight/contract/pipeline.py",
    "openflight/contract/model_contract.py",
])
def test_mutate_contract_source_stales_checker_checks(tmp_path, rel):
    # checker_source group: every check that runs the contract engine.
    # (the probe's four; baseline added — it also runs the checker)
    root = _make_sandbox(tmp_path)
    st = _mutate(root, rel, _append_comment)
    assert set(st["stale_checks"]) == {
        "battery", "heldout", "independent", "workflows", "baseline"}


