"""Phase 1: evidence graph record/status behavior (2026-10-14).

Schema v2 (2026-10-15): `record` writes a check entry only when that
check actually ran, with its result; `status` reports fresh / stale /
never run. The per-input mutation table lives in
test_evidence_mutation.py, which also guards the import closure.
"""
import json
import os
import shutil

import pytest

from openflight import evidence as EV

ALL_CHECKS = sorted(EV.CHECK_DEPS)


@pytest.fixture
def sandbox(tmp_path):
    """Copy every tracked artifact into tmp; never touches the real tree."""
    root = tmp_path / "repo"
    for group, rels in EV.ARTIFACT_GROUPS.items():
        for rel in rels:
            dst = root / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            if os.path.isfile(rel):
                shutil.copy(rel, dst)
            elif group == "generated_cxx":
                dst.write_text("// generated by openflight compile\n")
            elif group == "firmware_binary":
                dst.write_bytes(b"\x7fELF-fake-firmware")
    return root


def test_record_with_results_then_status_fresh(sandbox):
    EV.record(root=str(sandbox),
              results={c: {"result": "ok"} for c in ALL_CHECKS})
    st = EV.status(root=str(sandbox))
    assert st["stale_checks"] == []
    assert st["never_run_checks"] == []
    assert st["claims_at_risk"] == []
    assert st["claims_unverified"] == []
    assert (sandbox / "results/evidence.json").exists()
    doc = json.loads((sandbox / "results/evidence.json").read_text())
    assert doc["schema_version"] == 2
    assert set(doc["checks"]) == set(ALL_CHECKS)
    assert doc["checks"]["battery"]["result"] == "ok"


def test_recorded_fail_result_is_surfaced(sandbox):
    EV.record(root=str(sandbox),
              results={c: {"result": "ok"} for c in ALL_CHECKS}
              | {"heldout": {"result": "fail"}})
    st = EV.status(root=str(sandbox))
    assert st["checks"]["heldout"]["result"] == "fail"
    assert st["checks"]["heldout"]["status"] == "fresh"  # inputs unchanged


def test_delete_recorded_artifact_goes_stale(sandbox):
    EV.record(root=str(sandbox),
              results={c: {"result": "ok"} for c in ALL_CHECKS})
    os.unlink(sandbox / "learned_observer.pt")
    st = EV.status(root=str(sandbox))
    assert "parity" in st["stale_checks"]
    reasons = st["checks"]["parity"]["reasons"]
    assert any("missing" in r for r in reasons)


def test_status_lists_sidecar_limitations_and_blanket(sandbox):
    EV.record(root=str(sandbox),
              results={c: {"result": "ok"} for c in ALL_CHECKS})
    side = {
        "schema_version": 1,
        "confirm_mode": "blanket",
        "blanket": ["features[0].source.quantity"],
        "not_individually_verified": ["features[0].source.quantity"],
        "limitations": [{"code": "W301", "reason": "clip not applied"}],
        "provenance": {},
    }
    sp = sandbox / "examples/quadrotor_adapter/model.yaml.provenance.json"
    sp.write_text(json.dumps(side))
    st = EV.status(root=str(sandbox))
    lims = st["unresolved_limitations"]
    assert any("W301" in json.dumps(x) for x in lims)
    assert any("features[0].source.quantity" in json.dumps(x)
               for x in lims)


def test_cli_record_without_results_reports_never_run(sandbox, capsys):
    from openflight import cli
    rc = cli.main(["evidence", "record", "--root", str(sandbox)])
    assert rc == 0
    rc = cli.main(["evidence", "status", "--root", str(sandbox)])
    assert rc == 0  # never run is not an error
    out = capsys.readouterr().out
    assert "never run" in out
    assert "claims without live evidence" in out


def test_cli_status_stale_exits_one(sandbox, capsys):
    from openflight import cli
    EV.record(root=str(sandbox),
              results={c: {"result": "ok"} for c in ALL_CHECKS})
    p = sandbox / "openflight/contract/checker.py"
    original = p.read_bytes()
    try:
        p.write_bytes(original + b"\n# drift\n")
        rc = cli.main(["evidence", "status", "--root", str(sandbox)])
        assert rc == 1
        out = capsys.readouterr().out
        assert "battery" in out and "STALE" in out
    finally:
        p.write_bytes(original)


def test_status_without_record_is_diagnosed(sandbox, capsys):
    st = EV.status(root=str(sandbox))
    assert st["error"]  # diagnosed, not a traceback
