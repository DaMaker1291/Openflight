"""Phase 1: evidence graph with invalidation (2026-10-14).

Checks record the sha256 of the artifacts they read (results/evidence.json);
`openflight evidence status` re-hashes and lists stale checks plus the
CLAIMS.md claims that depend on them. Mutating ONE input must stale
exactly the checks that read it — no others.
"""
import json
import os
import shutil

import pytest

from openflight import evidence as EV

REPO_FILES = [
    "examples/quadrotor_adapter/example_weights.pt",
    "examples/quadrotor_adapter/model_contract.yaml",
    "examples/quadrotor_adapter/drone_contract.yaml",
    "openflight/contract/checker.py",
    "results/example_disturbance12/experiment_manifest.json",
]


@pytest.fixture
def sandbox(tmp_path):
    root = tmp_path / "repo"
    for rel in REPO_FILES:
        dst = root / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(rel, dst)
    cpp = root / "build/model_adapters.cpp"
    cpp.parent.mkdir(parents=True, exist_ok=True)
    cpp.write_text("// generated by openflight compile\n")
    fw = root / "firmware/esp32/build/openflight_bench.bin"
    fw.parent.mkdir(parents=True, exist_ok=True)
    fw.write_bytes(b"\x7fELF-fake-firmware")
    EV.record(root=str(root))
    return root


def _mutate(root, rel, transform):
    p = root / rel
    p.write_text(transform(p.read_text()))


def _mutate_bytes(root, rel, suffix=b""):
    p = root / rel
    p.write_bytes(p.read_bytes() + suffix)


def test_record_then_status_fresh(sandbox):
    st = EV.status(root=str(sandbox))
    assert st["stale_checks"] == []
    assert st["claims_at_risk"] == []
    assert (sandbox / "results/evidence.json").exists()


def test_mutate_weights_stales_every_check_that_reads_weights(sandbox):
    _mutate_bytes(sandbox, "examples/quadrotor_adapter/example_weights.pt",
                  b"\ncorrupted")
    st = EV.status(root=str(sandbox))
    # exactly the weight-reading checks; qemu reads the firmware binary,
    # which transitively embeds weights only after a rebuild
    assert set(st["stale_checks"]) == {
        "battery", "heldout", "independent", "workflows", "parity", "build"}
    assert "qemu" not in st["stale_checks"]
    assert "C5" in st["claims_at_risk"] and "C1" in st["claims_at_risk"]
    assert "C10" in st["claims_at_risk"]  # reproducibility depends on all


def test_mutate_sensor_contract_stales_checker_checks_only(sandbox):
    _mutate(sandbox, "examples/quadrotor_adapter/drone_contract.yaml",
            lambda t: t.replace("radians_per_second", "degrees_per_second"))
    st = EV.status(root=str(sandbox))
    assert set(st["stale_checks"]) == {
        "battery", "heldout", "independent", "workflows"}
    assert "parity" not in st["stale_checks"]
    assert "build" not in st["stale_checks"]
    assert set(st["claims_at_risk"]) == {"C5", "C6", "C10"}


def test_mutate_checker_source_stales_checker_checks_only(sandbox):
    _mutate(sandbox, "openflight/contract/checker.py",
            lambda t: t + "\n# one-line change\n")
    st = EV.status(root=str(sandbox))
    assert set(st["stale_checks"]) == {
        "battery", "heldout", "independent", "workflows"}
    assert set(st["claims_at_risk"]) == {"C5", "C6", "C10"}


def test_mutate_compiler_flags_stales_parity_build_qemu(sandbox):
    _mutate(sandbox,
            "results/example_disturbance12/experiment_manifest.json",
            lambda t: t.replace('"runs": 100', '"runs": 50')
            if '"runs": 100' in t else t + "\n")
    st = EV.status(root=str(sandbox))
    assert set(st["stale_checks"]) == {"parity", "build", "qemu"}
    assert set(st["claims_at_risk"]) == {"C1", "C2", "C3", "C4",
                                         "C7", "C8", "C10"}


def test_mutate_confirmed_field_stales_dependent_checks(sandbox):
    """A confirmed field lives in the contract; changing it (e.g. the
    body-frame confirmation on the gyro features) must stale every check
    that read that contract."""
    _mutate(sandbox, "examples/quadrotor_adapter/model_contract.yaml",
            lambda t: t.replace("frame: body", "frame: px4_frd_body"))
    st = EV.status(root=str(sandbox))
    assert set(st["stale_checks"]) == {
        "battery", "heldout", "independent", "workflows", "build"}
    assert "parity" not in st["stale_checks"]
    assert "qemu" not in st["stale_checks"]


def test_mutate_generated_cxx_stales_parity_and_build(sandbox):
    _mutate(sandbox, "build/model_adapters.cpp",
            lambda t: t + "// changed\n")
    st = EV.status(root=str(sandbox))
    assert set(st["stale_checks"]) == {"parity", "build"}


def test_mutate_firmware_binary_stales_parity_and_qemu(sandbox):
    p = sandbox / "firmware/esp32/build/openflight_bench.bin"
    p.write_bytes(p.read_bytes() + b"x")
    st = EV.status(root=str(sandbox))
    assert set(st["stale_checks"]) == {"parity", "qemu"}


def test_delete_recorded_artifact_goes_stale(sandbox):
    os.unlink(sandbox / "examples/quadrotor_adapter/example_weights.pt")
    st = EV.status(root=str(sandbox))
    assert "battery" in st["stale_checks"]
    reasons = st["checks"]["battery"]["reasons"]
    assert any("missing" in r for r in reasons)


def test_status_lists_sidecar_limitations_and_blanket(sandbox):
    side = {
        "schema_version": 1,
        "confirm_mode": "blanket",
        "blanket": ["features[0].source.quantity"],
        "not_individually_verified": ["features[0].source.quantity"],
        "limitations": [{"code": "W301", "reason": "clip not applied"}],
        "provenance": {},
    }
    sp = sandbox / "examples/quadrotor_adapter/model.yaml.provenance.json"
    sp.write_text(json.dumps(side))
    st = EV.status(root=str(sandbox))
    lims = st["unresolved_limitations"]
    assert any("W301" in json.dumps(x) for x in lims)
    assert any("features[0].source.quantity" in json.dumps(x)
               for x in lims)


def test_cli_evidence_record_and_status(sandbox, capsys):
    from openflight import cli
    rc = cli.main(["evidence", "record", "--root", str(sandbox)])
    assert rc == 0
    rc = cli.main(["evidence", "status", "--root", str(sandbox)])
    assert rc == 0  # fresh
    out = capsys.readouterr().out
    assert "fresh" in out.lower() or "up to date" in out.lower()
    # now stale
    _mutate(sandbox, "examples/quadrotor_adapter/drone_contract.yaml",
            lambda t: t + "\n# drift\n")
    rc = cli.main(["evidence", "status", "--root", str(sandbox)])
    assert rc == 1
    out = capsys.readouterr().out
    assert "battery" in out and "stale" in out.lower()


def test_status_without_record_is_diagnosed(sandbox, capsys):
    os.unlink(sandbox / "results/evidence.json")
    st = EV.status(root=str(sandbox))
    assert st["error"]  # diagnosed, not a traceback
